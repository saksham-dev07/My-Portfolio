import { mkdir, readdir, readFile, unlink, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { optimize } from "svgo";

const root = fileURLToPath(new URL("../../", import.meta.url));
const assets = join(root, "src/assets");
const output = join(assets, "responsive");
await mkdir(output, { recursive: true });
// This directory contains only this script's generated image candidates.
for (const file of await readdir(output))
  if (/\.(avif|webp)$/.test(file) || file === "index.js")
    await unlink(join(output, file));
const inputs = [
  "profile.webp",
  "profile-studio.webp",
  "workstation-poster.webp",
];
for (const directory of ["projects", "certificates"])
  for (const file of await readdir(join(assets, directory)))
    if (/\.webp$/.test(file) && !file.includes("qr"))
      inputs.push(`${directory}/${file}`);

const imports = [],
  entries = [],
  stats = [];
for (const [index, input] of inputs.entries()) {
  const source = join(assets, input);
  const metadata = await sharp(source).metadata();
  const small = input.startsWith("profile");
  const widths = [
    ...new Set([
      ...(small ? [64, 128, 320, 640, 960] : [320, 640, 960, 1440]).filter(
        (width) => width < metadata.width,
      ),
      metadata.width,
    ]),
  ];
  const stem = input.replaceAll("/", "-").replace(/\.webp$/, "");
  imports.push(`import source${index} from ${JSON.stringify(`../${input}`)};`);
  const sets = { avif: [], webp: [] };
  const avifImports = [];
  const avifFiles = [];
  let avifUseful = true;
  for (const width of widths) {
    for (const format of ["avif", "webp"]) {
      if (format === "webp" && width === metadata.width) {
        sets.webp.push(`source${index} + " ${width}w"`);
        continue;
      }
      const filename = `${stem}-${width}.${format}`;
      const pipeline = sharp(source).resize({
        width,
        withoutEnlargement: true,
      });
      const encoded =
        format === "avif"
          ? pipeline.avif({
              quality: 85,
              chromaSubsampling: "4:4:4",
              effort: 5,
            })
          : pipeline.webp({ quality: 92, effort: 5 });
      await encoded.toFile(join(output, filename));
      const id = `image${index}_${format}_${width}`;
      const statement = `import ${id} from "./${filename}";`;
      if (format === "avif") {
        avifImports.push(statement);
        avifFiles.push(join(output, filename));
        if (width === metadata.width)
          avifUseful =
            (await readFile(join(output, filename))).length <
            (await readFile(source)).length;
      } else imports.push(statement);
      sets[format].push(`${id} + " ${width}w"`);
      if (width === widths[0])
        stats.push({
          input,
          format,
          width,
          bytes: (await readFile(join(output, filename))).length,
        });
    }
  }
  if (avifUseful) imports.push(...avifImports);
  else for (const file of avifFiles) await unlink(file);
  entries.push(
    `[source${index}]: { width: ${metadata.width}, height: ${metadata.height}, avif: ${avifUseful ? `[${sets.avif.join(", ")}].join(", ")` : "null"}, webp: [${sets.webp.join(", ")}].join(", ") }`,
  );
}
await writeFile(
  join(output, "index.js"),
  `// Generated by bun run assets:optimize. Originals are preserved.\n${imports.join("\n")}\nexport const responsiveImages = {\n${entries.join(",\n")}\n};\n`,
);

async function minifySvg(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory() && entry.name !== "responsive")
      await minifySvg(path);
    else if (entry.name.endsWith(".svg")) {
      const source = await readFile(path, "utf8");
      const result = optimize(source, { path, multipass: true });
      await writeFile(path, result.data);
    }
  }
}
await minifySvg(assets);
const logo = join(root, "public/logo.svg");
await writeFile(
  logo,
  optimize(await readFile(logo, "utf8"), { path: logo, multipass: true }).data,
);
console.log(
  JSON.stringify({ images: inputs.length, smallestCandidates: stats }, null, 2),
);
